// Ko-Chi Qigong — redirects from the old WordPress addresses (www.kochi-qigong.nl, until 2026)
// to the pages of this site. GitHub Pages cannot send real server redirects, so for every old
// address this writes a tiny page <old-path>/index.html that forwards the visitor at once.
// Google treats an instant meta refresh + canonical like a permanent (301) redirect.
//
// Edit REDIRECTS below, then run:   node tools/make-redirects.js
// (after node tools/sync-inspiratie.js, which makes the piece pages these point to)
// Removing a line here does NOT delete its folder; delete the folder yourself.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

// piece('n3') → that piece's own page (inspiratie-….html), looked up in assets/inspiratie-data.js
const vm = require('vm');
const data = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'assets/inspiratie-data.js'), 'utf8') + '\nthis.ITEMS = ITEMS;', data);
const piece = (id) => {
  const item = data.ITEMS.find((i) => i.id === id);
  if (!item) throw new Error('piece ' + id + ' is not in assets/inspiratie-data.js');
  return item.href;
};

// old path (without slashes)  →  new page (relative to the site root)
const REDIRECTS = {
  // pages
  'qigong': 'qigong.html',
  'coaching': 'coaching.html',
  'meditatie': 'meditatie.html',
  'workshops': 'voor-particulieren.html#Agenda',
  'op-het-werk': 'voor-organisaties.html',
  'tarieven': 'tarieven.html',
  'berichten': 'inspiratie.html',

  // categories
  'category/bewust': 'inspiratie.html',
  'category/flyer': 'inspiratie.html',
  'category/geluktraject': 'inspiratie.html',
  'category/nieuwsbrief': 'inspiratie.html',

  // posts → inspiratie pieces (ids from assets/inspiratie-data.js)
  'nieuwsbrief-april-2022': piece('n3'),
  'nieuwsbrief-augustus-2022': piece('n4'),
  'nieuwsbrief-oktober-2022': piece('n5'),
  'nieuwsbrief-januari-2023': piece('n2'),
  'nieuwsbrief-april-2023': piece('n6'),
  'nieuwsbrief-september-2023': piece('n7'),
  'nieuwsbrief-januari-2024': piece('n8'),
  'nieuwsbrief-eindejaar': piece('n9'),
  'nieuwsbrief-het-zaadje': piece('n10'),
  'geluk-week-8': piece('g1'),
  'bewust-zijn-met-energie': piece('e1'),               // posted apr 2023
  'bewust-zijn-met-energie-2023': piece('e2'),          // energie-2023.png
  'bewust-zijn-met-energie-2024': piece('e3'),          // energie-2024.png
  'bewust-zijn-met-energie-2024-juni': piece('e4'),
  'bewust-zijn-met-energie-2024-november': piece('e5'),
  'bewust-zijn-met-energie-2026-voorjaar': piece('e6'),
  'bewust-zijn-met-energie-28-juni': piece('e7'),
  'ontdek-de-sleutels-van-geluk': piece('g2'),          // "Geluk 2023"
  'ontdek-de-sleutels-van-geluk-2024': piece('g3'),
  'ontdek-de-sleutels-tot-geluk': piece('g4'),          // posted dec 2025
};

const MARK = '<!-- generated by tools/make-redirects.js -->';
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

let written = 0;
for (const [from, to] of Object.entries(REDIRECTS)) {
  const depth = from.split('/').length;
  const target = '../'.repeat(depth) + to;
  const file = path.join(root, from, 'index.html');

  if (!fs.existsSync(path.join(root, to.split(/[?#]/)[0]))) throw new Error(from + ': target ' + to + ' does not exist');
  if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').includes(MARK)) {
    throw new Error(from + '/index.html exists and was not made by this script; not overwriting');
  }

  const html = `<!DOCTYPE html>
${MARK}
<html lang="nl">
<head>
<meta charset="utf-8">
<title>Ko-Chi Qigong</title>
<link rel="canonical" href="${esc(target)}">
<meta http-equiv="refresh" content="0; url=${esc(target)}">
<script>
  // Same as the meta refresh, but keeps ?utm_… and #anchor from the old link.
  (function () {
    var t = ${JSON.stringify(target)}, q = location.search.slice(1), h = location.hash;
    if (q) t = t.replace(/(#|$)/, (t.indexOf('?') < 0 ? '?' : '&') + q + '$1');
    if (h && t.indexOf('#') < 0) t += h;
    location.replace(t);
  })();
</script>
</head>
<body>
<p>Deze pagina is verhuisd: <a href="${esc(target)}">ga verder</a>.</p>
</body>
</html>
`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old !== html) { fs.writeFileSync(file, html); written++; }
}
console.log(Object.keys(REDIRECTS).length + ' redirects, ' + written + ' file(s) written');
